class WLAN(object):
    scan_aps = []
    scan_error = False
    ok = set()
    last_ssid = None
    connects = []

    def __init__(self, iface):
        self._status = 0
        self.iface = iface
        WLAN.instances.append(self)

    def active(self, x=None):
        pass

    def scan(self):
        if WLAN.scan_error:
            raise OSError("scan fail")
        out = []
        for ssid, rssi in WLAN.scan_aps:
            out.append((ssid.encode(), b"\x00" * 6, 1, rssi, 4, False))
        return out

    def connect(self, s, p):
        WLAN.last_ssid = s
        WLAN.connects.append((s, p))
        if s in WLAN.ok:
            self._status = 3
        else:
            self._status = 4

    def disconnect(self):
        if self._status == 3:
            self._status = 0

    def status(self, arg=None):
        return -50 if arg == "rssi" else self._status

    def ifconfig(self):
        return ("192.168.1.8", "255.255.255.0", "192.168.1.1", "1.1.1.1")

    def config(self, **k):
        pass


